/**
 * Write src/font-manifest.ts from the vendored font files.
 *
 * Each font URL carries the first 16 hex digits of its SHA-256, so a URL names
 * one exact byte sequence and the Host can serve it as immutable. Re-run after
 * replacing a font file:
 *
 *   node packages/dsh-arbor-fonts/scripts/write-font-manifest.mjs
 */

import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const packageRoot = join(here, '..')
const fontsDir = join(packageRoot, 'fonts')

/** The four vendored faces, in stylesheet order. */
const FACES = [
  { file: 'ChillDIN-Regular.woff', family: 'Arbor ChillDIN', weight: 400, format: 'woff' },
  { file: 'ChillDIN-Medium.woff', family: 'Arbor ChillDIN', weight: 500, format: 'woff' },
  { file: 'ChillDIN-SemiBold.woff', family: 'Arbor ChillDIN', weight: 600, format: 'woff' },
  { file: 'ChillDINGothic_Std.woff2', family: 'Arbor ChillDIN Gothic', weight: 500, format: 'woff2' },
]

const faces = []
for (const face of FACES) {
  const bytes = await readFile(join(fontsDir, face.file))
  const sha256 = createHash('sha256').update(bytes).digest('hex')
  const path = `/api/arbor-fonts/${sha256.slice(0, 16)}/${face.file}`
  faces.push({
    ...face,
    mediaType: face.format === 'woff2' ? 'font/woff2' : 'font/woff',
    sha256,
    path,
    url: path.slice(1),
  })
}

const source = `/**
 * Generated by scripts/write-font-manifest.mjs from ../fonts. Do not edit by
 * hand: a changed font file must change its URL, which is what makes the
 * Host's immutable cache control honest.
 */

/** The two wire encodings the vendored files use. */
export type FontFormat = 'woff' | 'woff2'

/** One vendored face: what it is, where it is served, and its exact content. */
export interface FontFile {
  /** File name under ../fonts. */
  readonly file: string
  /** CSS family name the face belongs to. */
  readonly family: string
  /** The face's own weight. */
  readonly weight: number
  /** Wire encoding. */
  readonly format: FontFormat
  /** HTTP content type. */
  readonly mediaType: string
  /** Full SHA-256 of the file, used as the entity tag. */
  readonly sha256: string
  /** Absolute exact Fetch route under /api. */
  readonly path: string
  /** Document-relative URL for the stylesheet. */
  readonly url: string
}

/** Every face this plugin serves. */
export const FONT_FILES: readonly FontFile[] = ${JSON.stringify(faces, null, 2)}
`

await writeFile(join(packageRoot, 'src', 'font-manifest.ts'), source)
console.log(`wrote ${faces.length} faces to src/font-manifest.ts`)
